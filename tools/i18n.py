#!/usr/bin/env python3
"""
Farsi for Orbit: collect the interface text that needs translating, and build web/i18n.js.

  python3 tools/i18n.py collect <harvest.jsonl> <out.json>   strings seen on screen (HARVEST=... with the UI tests)
                                                             plus static text found in web/app.js; numbers become {n}
  python3 tools/i18n.py build <fa.json>...                    merge translations ({"English": "فارسی"}) into web/i18n.js

The app looks every piece of text up in web/i18n.js at runtime (see `tr` in app.js), so only exact phrases
are translated and anything people write themselves is left alone.
"""
import json, re, sys, os

ROOT = os.path.join(os.path.dirname(__file__), '..')
NUM = re.compile(r'\d+(?:[.,:]\d+)*')
CODE = re.compile(r'(=>|\(\)|\.value|var\(|;|px\b|^#|https?:|\.js$|\.png$|^[\w.-]+/[\w.-]+$|[{}](?!n\})|^[a-z][\w-]*$|^[A-Z_]+$|^\W+$)')


def norm(t):
    return NUM.sub('{n}', ' '.join(t.split()))


def keep(t):
    if not re.search(r'[A-Za-z]{2}', t) or len(t) > 400:
        return False
    if CODE.search(t.replace('{n}', '')):
        return False
    return True


def static(src):
    out = set()
    for tpl in re.findall(r'template: `(.*?)`', src, re.S):
        for frag in re.findall(r'>([^<>]+)<', tpl):
            for part in re.split(r'\{\{.*?\}\}', frag, flags=re.S):
                if part.strip():
                    out.add(part.strip())
        for expr in re.findall(r'\{\{(.*?)\}\}', tpl, re.S) + re.findall(r'(?:placeholder|aria-label|title)="([^"]+)"', tpl) + re.findall(r':[\w-]+="([^"]+)"', tpl):
            out.update(x.replace("\\'", "'") for x in re.findall(r"'((?:[^'\\]|\\.)+)'", expr))
    # strings in the code that reach the screen: toasts, labels, titles, list items
    code = re.sub(r'template: `.*?`', '', src, flags=re.S)
    for m in re.finditer(r"(?:say|tr)\(\s*'((?:[^'\\]|\\.)+)'", code):
        out.add(m.group(1).replace("\\'", "'"))
    for m in re.finditer(r"\b(?:l|t|s|title|body|desc|label|placeholder|e?text)\s*:\s*'((?:[^'\\]|\\.)+)'", code):
        out.add(m.group(1).replace("\\'", "'"))
    for arr in re.findall(r"\[\s*('(?:[^'\\]|\\.)+'(?:\s*,\s*'(?:[^'\\]|\\.)+')+)\s*,?\s*\]", code):
        for x in re.findall(r"'((?:[^'\\]|\\.)+)'", arr):
            if ' ' in x and x[0].isupper():
                out.add(x.replace("\\'", "'"))
    return out


def collect(harvest, out_path):
    seen = set()
    if harvest and os.path.exists(harvest):
        for line in open(harvest, encoding='utf8'):
            line = line.strip()
            if line:
                seen.add(json.loads(line))
    src = open(os.path.join(ROOT, 'web', 'app.js'), encoding='utf8').read()
    keys = {norm(t) for t in seen | static(src)}
    keys = sorted(k for k in keys if keep(k))
    json.dump(keys, open(out_path, 'w', encoding='utf8'), ensure_ascii=False, indent=0)
    print(len(keys), 'strings ->', out_path)


def build(paths):
    fa = {}
    for p in paths:
        fa.update(json.load(open(p, encoding='utf8')))
    fa = {k: v for k, v in fa.items() if isinstance(v, str) and v.strip() and v != k}
    body = json.dumps(fa, ensure_ascii=False, indent=0, sort_keys=True)
    with open(os.path.join(ROOT, 'web', 'i18n.js'), 'w', encoding='utf8') as f:
        f.write('/* Farsi interface text, keyed by the English it replaces ({n} stands for any number).\n'
                ' * Generated by tools/i18n.py build: edit the source JSON, not this file. */\n'
                'window.OrbitI18n = { fa: ' + body + ' };\n')
    print(len(fa), 'translations -> web/i18n.js')


if __name__ == '__main__':
    if sys.argv[1] == 'collect':
        collect(sys.argv[2], sys.argv[3])
    else:
        build(sys.argv[2:])
